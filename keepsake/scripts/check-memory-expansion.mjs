import assert from 'node:assert/strict';
import {foundPhotos,recordPhotoActivity} from '../src/lib/photoActivity.ts';
import {soundZoneGain} from '../src/lib/memoryAtmosphere.ts';
const now=100*86400000,photo={id:'a',src:'one',createdAt:1,categories:[],favorite:false,activity:{}};
const s={profile:{},archive:[photo],books:[],pins:[]};
assert.equal(foundPhotos(s,now).length,1);
assert.equal(foundPhotos({...s,archive:[{...photo,activity:undefined}]},now).length,0,'Unknown legacy history is never resurfaced');
assert.equal(foundPhotos({...s,profile:{foundPhotos:false}},now).length,0);
assert.equal(foundPhotos({...s,profile:{lastFoundPhotosAt:now-86400000}},now).length,0);
assert.equal(foundPhotos({...s,archive:[{...photo,createdAt:now-86400000}]},now).length,0);
const favored=recordPhotoActivity(s,{...s,archive:[{...photo,favorite:true}]},now);
const unfavored=recordPhotoActivity(favored,{...favored,archive:[{...favored.archive[0],favorite:false}]},now);
assert.equal(foundPhotos(unfavored,now+60*86400000).length,0,'Removing a favorite cannot erase meaningful history');
const printed=recordPhotoActivity(s,{...s,latestPrint:{src:'one'}},now);
assert.equal(foundPhotos({...printed,latestPrint:undefined},now+60*86400000).length,0);
const used=recordPhotoActivity(s,{...s,books:[{pages:[{elements:[{type:'photo',src:'one'}]}]}]},now);
assert.equal(foundPhotos({...used,books:[]},now+60*86400000).length,0,'Removing a used photo does not make it untouched');
assert.equal(soundZoneGain('left',false,false),1);assert.equal(soundZoneGain('left',false,true),.55);assert.equal(soundZoneGain('front',true,true),.65);
console.log('PASS rediscovery history, privacy of legacy data, opt-out, cooldowns and sound-zone gain rules.');
