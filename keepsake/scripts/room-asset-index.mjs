import fs from 'node:fs';
import path from 'node:path';

// The Woodland cabin is built by art/woodland-study/build.py; the other rooms keep their own folder.
const folders = {woodland: 'woodland-study', beachfront: 'beachfront', cyberpunk: 'cyberpunk'};

export function writeRoomAssetIndex(root) {
  const runtime = {};
  for (const [room, folder] of Object.entries(folders)) {
    const manifest = path.join(root, 'public/room', folder, 'asset-manifest.json');
    if (!fs.existsSync(manifest)) continue;
    const data = JSON.parse(fs.readFileSync(manifest, 'utf8'));
    runtime[room] = Object.fromEntries(
      Object.entries(data.qualities).map(([quality, asset]) => [
        quality,
        `/room/${folder}/${asset.file}?v=${asset.sha256.slice(0, 12)}`,
      ]),
    );
  }
  fs.mkdirSync(path.join(root, 'src/generated'), {recursive: true});
  fs.writeFileSync(
    path.join(root, 'src/generated/roomAssets.ts'),
    `// Generated by npm run assets:refresh and assets:woodland. Stable filenames, content-versioned URLs.\nexport const roomAssets = ${JSON.stringify(runtime, null, 2)} as const;\n`,
  );
}
